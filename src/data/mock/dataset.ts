const fy = (
  label: string,
  revenue: number | undefined,
  operatingIncome: number | undefined,
  netIncome: number | undefined,
  eps: number | undefined,
  bps: number | undefined,
  dividendPerShare: number | undefined,
  isForecast = false
): FiscalYear => ({ label, revenue, operatingIncome, netIncome, eps, bps, dividendPerShare, isForecast });

const daysAgo = (n: number) => {
  const d = new Date();
  d.setDate(d.getDate() - n);
  return d.toISOString();
};
const daysAhead = (n: number) => {
  const d = new Date();
  d.setDate(d.getDate() + n);
  return d.toISOString().slice(0, 10);
};

let newsSeq = 0;
const news = (
  title: string,
  source: string,
  ago: number,
  summary?: string,
  impactHint: NewsItem['impactHint'] = 'unknown'
): NewsItem => ({
  id: `n${++newsSeq}`,
  title,
  source,
  publishedAt: daysAgo(ago),
  summary,
  impactHint,
});

