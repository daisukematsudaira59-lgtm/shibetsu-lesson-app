/**
 * 予算に対する一般的な考え方。金額の断定はしない。
 */
export function budgetGuidance(budget: number): string[] {
  const lines: string[] = [];
  if (budget < 50000) {
    lines.push('この金額なら、まず投資信託1本、または S株で2〜3銘柄に分けるのが現実的な範囲です。');
  } else if (budget < 300000) {
    lines.push(
      '個別株なら3〜4銘柄に分ける、投資信託なら1〜2本にまとめる、あるいは半分ずつという分け方が一般的です。全額を1つに入れる必要はありません。'
    );
  } else {
    lines.push('複数の銘柄と投資信託を組み合わせやすい金額です。それでも、一度に全額を使わず何回かに分けて買う方法を検討してください。');
  }
  lines.push('いずれの場合も、生活費・急な出費に使うお金は別に確保したうえで、残りで考えます。');
  return lines;
}
